/** Native detailed mask coverage; supersamples only authored geometry, never source artwork. */
export function faceBrowCoverage(x: number, y: number, polygon: readonly (readonly [number, number])[]) {
  let samples = 0;
  for (let sx = 0; sx < 4; sx++) for (let sy = 0; sy < 4; sy++) {
    const px = x + (sx + 0.5) / 4, py = y + (sy + 0.5) / 4; let inside = false;
    for (let a = 0, b = polygon.length - 1; a < polygon.length; b = a++) {
      const [ax, ay] = polygon[a]!, [bx, by] = polygon[b]!;
      if ((ay > py) !== (by > py) && px < (bx - ax) * (py - ay) / (by - ay) + ax) inside = !inside;
    }
    if (inside) samples++;
  }
  return Math.round(samples * 255 / 16);
}

