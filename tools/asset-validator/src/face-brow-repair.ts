/** Reference / selected previous fit / current candidate; magnification changes inspection only. */
export function faceBrowComparison(reference: RgbaImage, previous: RgbaImage, current: RgbaImage) {
  const crop = { x: 435, y: 148, width: 150, height: 80 }, scale = 4;
  const out = blankImage(crop.width * scale * 3, crop.height * scale);
  for (const [column, image] of [reference, previous, current].entries()) for (let y = 0; y < out.height; y++) for (let x = 0; x < crop.width * scale; x++) {
    const i = ((crop.y + Math.floor(y / scale)) * 1024 + crop.x + Math.floor(x / scale)) * 4, j = (y * out.width + column * crop.width * scale + x) * 4;
    const alpha = image.data[i + 3]! / 255, checker = (Math.floor(x / 32) + Math.floor(y / 32)) % 2 ? 195 : 235;
    for (let c = 0; c < 3; c++) out.data[j + c] = Math.round(image.data[i + c]! * alpha + checker * (1 - alpha));
    out.data[j + 3] = 255;
  }
  return out;
}
